#!/usr/bin/env bash
# Seed the `media-setup` Secret on the MEDIA cluster (calamansi-intel, .81) from
# Bitwarden. The media cluster has NO External Secrets operator, so this is applied
# out of band. media-stack-setup.sh reads these values to wire the *arr stack.
#
#   BWS_ACCESS_TOKEN=<machine-account-token> ./scripts/media-setup-secret.sh
#
# The *arr API keys come from Bitwarden by default. Pass KEYS_FROM=pods after a
# PVC restore: the app regenerates its key, so the Bitwarden copy is stale and
# pushing it into the Secret would break media-mcp / the arr-auth bypass.
#   KEYS_FROM=pods BWS_ACCESS_TOKEN=... ./scripts/media-setup-secret.sh
set -euo pipefail
export NIXPKGS_ALLOW_UNFREE="${NIXPKGS_ALLOW_UNFREE:-1}"
: "${BWS_ACCESS_TOKEN:?set BWS_ACCESS_TOKEN to the Bitwarden machine-account token}"
HOST="${HOST:-192.168.2.81}"
KEYS_FROM="${KEYS_FROM:-bitwarden}" # bitwarden | pods
NS="${NS:-media}"

bws() { nix run --impure nixpkgs#bws -- "$@"; }
jq()  { nix run nixpkgs#jq -- "$@"; }
b64() { printf %s "$1" | base64 -w0; }

sec="$(bws secret list --output json 2>/dev/null)"
get() { printf '%s' "$sec" | jq -r --arg k "$1" '.[]|select(.key==$k).value'; }

# API keys are generated by the *arr apps themselves, so Bitwarden is not their
# original source. The canonical copy nonetheless lives in Bitwarden Secrets
# Manager (`<app>-api-key`, seeded once from the running pods) so a media PVC wipe
# or host rebuild can't strand us with keys that exist only inside `/config`.
# If a BWS secret is absent we fall back to scraping the pod, which keeps this
# script usable for bootstrapping a brand-new stack.
appkey() { # <namespace> <deploy> <file> <xml-tag>
  ssh "root@$HOST" "k3s kubectl -n $1 exec deploy/$2 -- sed -n 's/.*<$4>\([^<]*\)<.*/\1/p' $3" 2>/dev/null | tr -d '\r' | head -1
}
sabkey() { # sabnzbd keeps its key in an ini, not xml
  ssh "root@$HOST" "k3s kubectl -n downloads exec deploy/sabnzbd -- sed -n 's/^api_key = //p' /config/sabnzbd.ini" 2>/dev/null | tr -d '\r' | head -1
}
prefer() { # <bws-key> <fallback-fn> [args...] — Bitwarden first, pod scrape second
  local v=""
  if [ "$KEYS_FROM" = bitwarden ]; then v="$(get "$1")"; fi
  shift
  if [ -n "$v" ] && [ "$v" != "null" ]; then printf '%s' "$v"; else "$@" 2>/dev/null; fi
}
sonarr_key="$(prefer sonarr-api-key appkey media sonarr /config/config.xml ApiKey)"
radarr_key="$(prefer radarr-api-key appkey media radarr /config/config.xml ApiKey)"
prowlarr_key="$(prefer prowlarr-api-key appkey media prowlarr /config/config.xml ApiKey)"
sab_key="$(prefer sabnzbd-api-key sabkey)"

# Never apply a media-setup with an empty key: a silent empty value looks like
# success but leaves media-mcp and the arr-auth bypass 401ing.
for k in "$sonarr_key" "$radarr_key" "$prowlarr_key" "$sab_key"; do
  [ -n "$k" ] || { echo "ERROR: empty *arr API key captured (KEYS_FROM=$KEYS_FROM) — not applying" >&2; exit 1; }
done

cat <<EOF | ssh "root@$HOST" "k3s kubectl apply -f -"
apiVersion: v1
kind: Secret
metadata:
  name: media-setup
  namespace: $NS
type: Opaque
data:
  qbt-password: $(b64 "$(get qbittorrent-password)")
  nzbgeek-api: $(b64 "$(get nzbgeek_api)")
  jellyfin-admin-user: $(b64 "$(get jellyfin-admin-user)")
  jellyfin-admin-pass: $(b64 "$(get jellyfin-admin-pass)")
  jellyfin-anton: $(b64 "$(get jellyfin-anton)")
  jellyfin-delfin: $(b64 "$(get jellyfin-delfin)")
  jellyfin-ciceley: $(b64 "$(get jellyfin-ciceley)")
  jellyfin-guest: $(b64 "$(get jellyfin-guest)")
  jellyfin-trish: $(b64 "$(get jellyfin-trish)")
  opensubtitles-user: $(b64 "$(get opensubtitles-user)")
  opensubtitles-pass: $(b64 "$(get opensubtitles-pass)")
  sonarr-api-key: $(b64 "$sonarr_key")
  radarr-api-key: $(b64 "$radarr_key")
  prowlarr-api-key: $(b64 "$prowlarr_key")
  sabnzbd-api-key: $(b64 "$sab_key")
  lazylibrarian-api-key: $(b64 "$(get lazylibrarian-api-key)")
---
# Pull secret for private GHCR images (ghcr.io/bismigel/*) — the media cluster has
# no ESO, so it is seeded here from Bitwarden alongside media-setup.
apiVersion: v1
kind: Secret
metadata:
  name: ghcr-secret
  namespace: $NS
type: kubernetes.io/dockerconfigjson
data:
  .dockerconfigjson: $(b64 "{\"auths\":{\"ghcr.io\":{\"username\":\"$(get ghcr-user)\",\"password\":\"$(get ghcr-token)\",\"auth\":\"$(printf %s "$(get ghcr-user):$(get ghcr-token)" | base64 -w0)\"}}}")
EOF
echo "media-setup secret applied on $HOST ($NS)"
